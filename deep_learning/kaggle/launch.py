"""Run ``deep_learning.train`` on a Kaggle GPU and bring the results back into ``artifacts/``.

    python -m deep_learning.kaggle.launch push  --slug metr-dl-main --models gru st_gat --seeds 42
    python -m deep_learning.kaggle.launch status --slug metr-dl-main
    python -m deep_learning.kaggle.launch fetch  --slug metr-dl-main

``push`` pins the run to the current commit, which must already be on GitHub: the Kaggle session
clones exactly that commit, downloads and checksums the raw data, rebuilds ``data/processed``
(checked against the committed split and scaler) and trains. Kernels are private.
Auth: the Kaggle CLI reads ``~/.kaggle/access_token`` (never stored in the repository).
"""
from __future__ import annotations

import argparse
import json
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from src import config

REPO = "https://github.com/agrawalshreyansh/T005_MLDL_Project.git"
KAGGLE = str(Path(sys.executable).with_name("kaggle"))

KERNEL = '''"""Generated by deep_learning/kaggle/launch.py - trains at commit {commit}."""
import os, shutil, subprocess, sys

def sh(cmd, **kw):
    print("+", cmd, flush=True)
    subprocess.run(cmd, shell=True, check=True, **kw)

sh("nvidia-smi --query-gpu=name,memory.total --format=csv || true")
sh("git clone -q {repo} repo")
os.chdir("repo")
sh("git checkout -q {commit}")
sh(sys.executable + " -m pip install -q torch_geometric h5py")
env = dict(os.environ, **{env})
sh(sys.executable + " -m deep_learning.prepare_data --download", env=env)
try:
    sh(sys.executable + " -m deep_learning.train {train_args}", env=env)
finally:  # keep whatever finished, even if a later run fails
    shutil.copytree("artifacts", "/kaggle/working/artifacts", dirs_exist_ok=True)
'''


def kaggle(*args: str, capture: bool = False) -> str:
    out = subprocess.run([KAGGLE, *args], check=True, text=True, capture_output=capture)
    return out.stdout if capture else ""


def username() -> str:
    for line in kaggle("config", "view", capture=True).splitlines():
        if line.strip().startswith("- username:"):
            return line.split(":", 1)[1].strip()
    raise RuntimeError("could not read the Kaggle username from `kaggle config view`")


def head_commit() -> str:
    commit = subprocess.check_output(["git", "rev-parse", "HEAD"], text=True).strip()
    remote = subprocess.check_output(["git", "branch", "-r", "--contains", commit], text=True).strip()
    if not remote:
        raise SystemExit(f"commit {commit[:8]} is not on GitHub yet - push the branch first")
    if subprocess.check_output(["git", "status", "--porcelain", "--untracked-files=no"], text=True).strip():
        print("warning: uncommitted changes are NOT part of the Kaggle run", file=sys.stderr)
    return commit


def push(args) -> None:
    commit = head_commit()
    train_args = ["--models", *args.models, "--seeds", *map(str, args.seeds), *args.extra]
    env = {"TFC_RUN_MODE": "smoke"} if args.smoke else {}
    with tempfile.TemporaryDirectory() as tmp:
        Path(tmp, "kernel.py").write_text(KERNEL.format(
            commit=commit, repo=REPO, env=repr(env), train_args=shlex.join(train_args)))
        Path(tmp, "kernel-metadata.json").write_text(json.dumps({
            "id": f"{username()}/{args.slug}", "title": args.slug, "code_file": "kernel.py",
            "language": "python", "kernel_type": "script", "is_private": True,
            "enable_gpu": True, "enable_internet": True, "machine_shape": args.machine,
            "dataset_sources": [], "competition_sources": [], "kernel_sources": [],
        }, indent=2))
        kaggle("kernels", "push", "-p", tmp)
    print(f"pushed {args.slug} at commit {commit[:8]}: {' '.join(train_args)}")


def status(args) -> None:
    kaggle("kernels", "status", f"{username()}/{args.slug}")


def fetch(args) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        kaggle("kernels", "output", f"{username()}/{args.slug}", "-p", tmp, "-o")
        src = Path(tmp, "artifacts")
        if not src.is_dir():
            raise SystemExit(f"no artifacts in the output of {args.slug} (did the run fail? see its log)")
        shutil.copytree(src, config.ARTIFACTS, dirs_exist_ok=True)
        logs = list(Path(tmp).glob("*.log"))
        for log in logs:
            shutil.copy(log, config.METRICS_DIR / f"kaggle_{args.slug}.log")
    print("copied into", config.ARTIFACTS.relative_to(config.PROJECT_ROOT),
          "|", ", ".join(sorted(p.stem for p in config.MODELS_DIR.glob("dl_*.pt"))))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("push")
    p.add_argument("--slug", required=True)
    p.add_argument("--models", nargs="+", required=True)
    p.add_argument("--seeds", nargs="+", type=int, default=[config.SEED])
    p.add_argument("--smoke", action="store_true", help="TFC_RUN_MODE=smoke on Kaggle (2 epochs, tiny subsets)")
    p.add_argument("--machine", default="NvidiaTeslaT4")
    p.add_argument("extra", nargs=argparse.REMAINDER, help="after --, passed through to deep_learning.train")
    for name in ("status", "fetch"):
        sub.add_parser(name).add_argument("--slug", required=True)
    args = ap.parse_args()
    if getattr(args, "extra", None) and args.extra[0] == "--":
        args.extra = args.extra[1:]
    {"push": push, "status": status, "fetch": fetch}[args.cmd](args)


if __name__ == "__main__":
    main()
